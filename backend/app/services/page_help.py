def guide_path(path: str) -> str | None:
    """只接受本站已登錄的路徑，不使用前端提供的標題決定說明內容。"""
    if not path.startswith("/") or path.startswith("//") or "\\" in path or any(ord(c) < 32 for c in path):
        return None
    parsed = urlsplit(path)
    route = parsed.path.rstrip("/")
    if route == "/manager" and parse_qs(parsed.query).get("view", [""])[0] not in ("", "inquiries", "asks", "routes"):
        return None
    if route in ("/orders", "/products"):
        view = parse_qs(parsed.query).get("view", [""])[0]
        if view in ("products", "promotions"):
            return f"/{view}"
    if route.startswith("/oa/new/"):
        return "/oa/forms"
    return next((key for key in GUIDES if route == key or route.startswith(key + "/")), None)


def answer(page: str, topic: str) -> str | None:
    guide = GUIDES.get(page)
    return guide["topics"].get(topic) if guide else None


def demo_path(page: str, current_path: str) -> str | None:
    if page not in GUIDES:
        return None
    return current_path if guide_path(current_path) == page else page
